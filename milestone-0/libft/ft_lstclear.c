#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list *tmp;

	if (!lst || !del)
		return ;
	while (*lst)
	{
		tmp = (*lst)->next;      // save next BEFORE freeing
		ft_lstdelone(*lst, del); // free current node (content + node)
		*lst = tmp;              // advance head
	}
	*lst = NULL; // already NULL, but explicit
}